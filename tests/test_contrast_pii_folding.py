"""접기 대조 스크립트가 **방향을 가려서** 센다.

**왜 이 파일이 있는가.** 안전장치를 넓히는 수정은 미탐만 닫는 것이 아니라 오탐도 함께
연다. 그래서 초안 판정 절이 *"양방향을 함께 잰다 — 미탐이 닫히는 건수와 정상 근거의
에코가 기각되는 건수를 같은 대조에서 낸다. **오탐이 늘면 채택하지 않는다**"* 를 요구한다.

그런데 그 계기가 방향을 못 가르고 있었다. 새로 기각된 건수를 한 칸에 담으면 **우회를
닫은 건수와 정상 초안을 새로 기각한 건수가 같은 칸에서 커진다** — 접기를 넓힐수록 그
칸이 커지므로 오탐 증가가 성과처럼 읽히고, "오탐이 늘면 채택하지 않는다" 를 이 대조로는
발동시킬 수 없다. 실제로 정상 문자열 하나(`A_1588_0000`)를 넣으면 출력이
`미탐 닫힘 1건 · 정상 에코 오기각 0건` 이었다.

이 파일이 지키는 것은 **네 칸이 서로 다른 것을 센다**는 계약이다. 라벨이 없는 초안은
성과 칸에도 오탐 칸에도 넣지 않는다 — 모르는 것을 아는 것처럼 세지 않는다.
"""

from __future__ import annotations

import pytest
from scripts.contrast_pii_folding import (
    Case,
    VerdictContrast,
    l1_fixture_cases,
    verdict_contrast,
)

#: 근거에 없는 정상 문자열. 밑줄이 번호 구분자로 접히면서 대표번호 모양이 된다 —
#: 이 저장소의 사유 코드·근거 ID·컬럼명이 밑줄을 쓰므로 실제로 있을 수 있는 모양이다.
_정상_초안 = "처리 코드는 A_1588_0000 입니다."


def _대조(*cases: Case) -> VerdictContrast:
    return verdict_contrast("검사", cases, census=True)


def test_새로_기각된_정상_초안은_오탐_칸에_들어간다() -> None:
    """**이 검사가 이 파일의 이유다.** 고치기 전에는 이 건이 미탐 닫힘으로 셌다."""
    결과 = _대조(
        Case(
            case_id="정상",
            draft_texts=[_정상_초안],
            evidence_texts=["처리 안내입니다."],
            우회인가=False,
        )
    )

    assert 결과.새_오탐 == ("정상",)
    assert 결과.미탐_닫힘 == (), "정상 초안의 새 기각이 성과 칸에 들어가면 계기가 거짓말을 한다"


def test_새로_기각된_우회_초안은_성과_칸에_들어간다() -> None:
    """양성 대조 — 전부 오탐으로 세는 계기도 계기가 아니다."""
    결과 = _대조(
        Case(
            case_id="우회",
            draft_texts=["담당자 번호는 010_9999_8888 입니다."],
            evidence_texts=["담당자 안내입니다."],
            우회인가=True,
        )
    )

    assert 결과.미탐_닫힘 == ("우회",)
    assert 결과.새_오탐 == ()


def test_라벨_없는_초안은_어느_칸에도_들어가지_않는다() -> None:
    """대역 초안에는 라벨이 없다 — 방향을 단정하면 그 단정이 곧 수치가 된다."""
    결과 = _대조(
        Case(
            case_id="무라벨",
            draft_texts=[_정상_초안],
            evidence_texts=["처리 안내입니다."],
            우회인가=None,
        )
    )

    assert 결과.분류_불가 == ("무라벨",)
    assert 결과.미탐_닫힘 == ()
    assert 결과.새_오탐 == ()


def test_헤드라인이_네_칸을_구분해_적는다() -> None:
    """문면 검사 — 칸을 갈라 놓고 요약 줄이 도로 뭉치면 읽는 사람에게는 그대로다."""
    결과 = _대조(
        Case(case_id="정상", draft_texts=[_정상_초안], evidence_texts=["안내"], 우회인가=False),
        Case(case_id="무라벨", draft_texts=[_정상_초안], evidence_texts=["안내"], 우회인가=None),
    )

    문면 = 결과.headline

    assert "새 오탐 1건" in 문면
    assert "미탐 닫힘 0건" in 문면
    assert "분류 불가 1건" in 문면


def test_판정이_안_뒤집히면_어느_칸도_안_늘어난다() -> None:
    """음성 대조 — 아무 케이스나 담는 칸이면 위 검사들이 무의미하다."""
    결과 = _대조(
        Case(
            case_id="에코",
            draft_texts=["연락처는 010-1234-5678 입니다."],
            evidence_texts=["연락처는 010-1234-5678 입니다."],
            우회인가=False,
        )
    )

    assert (결과.미탐_닫힘, 결과.새_오탐, 결과.분류_불가, 결과.기각_풀림) == ((), (), (), ())


# ── 실물 채점표 위에서의 계약 ────────────────────────────────────────────────


def test_채점표_전수_대조가_새_오탐_0_건이다() -> None:
    """채택 조건 그 자체다 — 이 값이 0 이 아니면 접기 확대를 채택하지 않는다.

    실물에 붙는 검사이므로 **모양이 아니라 편입 조건만** 지킨다: 픽스처가 늘어도 새
    오탐이 0 이면 통과한다. 특정 건수를 박으면 채점표가 늘 때마다 깨진다.
    """
    결과 = verdict_contrast("L1 픽스처", l1_fixture_cases(), census=True)

    assert 결과.새_오탐 == ()
    assert 결과.미탐_닫힘, "우회 픽스처가 하나도 안 잡히면 대조가 아무것도 재지 않은 것이다"


@pytest.mark.parametrize("우회인가", [True, False])
def test_라벨은_픽스처의_기대_판정에서_유도한다(우회인가: bool) -> None:
    """라벨을 손으로 적으면 픽스처가 늘 때 조용히 어긋난다 — 두 종류가 실제로 다 있다."""
    라벨들 = {case.우회인가 for case in l1_fixture_cases()}

    assert 우회인가 in 라벨들
    assert None not in 라벨들, "채점표 케이스는 전부 라벨이 있어야 한다"
